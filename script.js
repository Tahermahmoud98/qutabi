function parseUploadedFile(file) {
    const fileName = file.name.toLowerCase();
    const isExcel = fileName.endsWith('.xlsx') || fileName.endsWith('.xls') || fileName.endsWith('.xlsm') || fileName.endsWith('.xlsb');
    
    if (isExcel && typeof XLSX !== 'undefined') {
        const reader = new FileReader();
        reader.onload = function(e) {
            try {
                const data = new Uint8Array(e.target.result);
                const workbook = XLSX.read(data, { type: 'array' });
                let allLines = [];

                for (let sIdx = 0; sIdx < workbook.SheetNames.length; sIdx++) {
                    const sheetName = workbook.SheetNames[sIdx];
                    const worksheet = workbook.Sheets[sheetName];
                    if (!worksheet) continue;

                    const rawRows = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: '' });
                    if (rawRows && rawRows.length > 0) {
                        const lines = extractTargetColumnsFromMatrix(rawRows);
                        if (lines.length > 0) {
                            allLines = lines;
                            break;
                        }
                    }
                }

                if (allLines.length === 0 && workbook.SheetNames.length > 0) {
                    const worksheet = workbook.Sheets[workbook.SheetNames[0]];
                    const rawRows = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: '' });
                    if (rawRows && rawRows.length > 0) {
                        rawRows.forEach(row => {
                            const cells = row.map(c => String(c !== null && c !== undefined ? c : '').trim()).filter(c => c !== '');
                            if (cells.length > 0) allLines.push(cells.join('\t'));
                        });
                    }
                }

                if (allLines.length > 0) {
                    document.getElementById('namesInput').value = allLines.join('\n');
                    onInputChanged();
                    closeDataModal();
                    processNames();
                    showToast(currentLang === 'en' ? 'Excel loaded!' : 'مەلەفێ إکسل ب سەرکەفتی هاتە وەرگرتن!');
                } else {
                    alert(currentLang === 'en' ? 'The uploaded Excel file contains no data!' : 'ملف الإكسل المرفوع لا يحتوي على بيانات!');
                }
            } catch (err) {
                console.error("Excel parse error:", err);
                alert(currentLang === 'en' ? 'Error reading Excel file.' : 'حدث خطأ أثناء قراءة ملف الإكسل.');
            }
        };
        reader.readAsArrayBuffer(file);
    } else {
        const reader = new FileReader();
        reader.onload = function(evt) {
            const text = evt.target.result;
            const rawLines = text.split(/\r?\n/).filter(l => l.trim().length > 0);
            if (rawLines.length > 0) {
                const firstLine = rawLines[0];
                let sep = '\t';
                if (firstLine.includes('\t')) sep = '\t';
                else if (firstLine.includes(',')) sep = ',';
                else if (firstLine.includes(';')) sep = ';';

                const matrix = rawLines.map(l => l.split(sep));
                const lines = extractTargetColumnsFromMatrix(matrix);
                document.getElementById('namesInput').value = lines.length > 0 ? lines.join('\n') : text;
            } else {
                document.getElementById('namesInput').value = text;
            }
            onInputChanged();
            closeDataModal();
            processNames();
            showToast(currentLang === 'en' ? 'Data imported!' : 'داتا ب سەرکەفتی هاتە وەرگرتن!');
        };
        reader.readAsText(file, 'UTF-8');
    }
}

function extractTargetColumnsFromMatrix(matrix) {
    if (!matrix || matrix.length === 0) return [];

    let headerRowIdx = -1;
    let nameCol = -1;
    let motherCol = -1;
    let gradeCol = -1;
    let sectionCol = -1;

    const isSchoolOrgWord = (txt) => {
        const lower = txt.toLowerCase();
        return lower.includes('قوتابخان') || lower.includes('مدرسة') || lower.includes('پەروەرد') || lower.includes('تربية') || lower.includes('مديرية') || lower.includes('حکومی') || lower.includes('لۆکاڵ') || lower.includes('حكومي');
    };

    for (let i = 0; i < Math.min(15, matrix.length); i++) {
        const row = matrix[i];
        if (!row || !Array.isArray(row)) continue;

        row.forEach((cellVal, colIdx) => {
            if (cellVal === null || cellVal === undefined) return;
            const str = String(cellVal).trim().toLowerCase();
            if (!str) return;

            if (str.includes('دەیک') || str.includes('دایک') || str.includes('ام') || str.includes('أم') || str.includes('mother') || str.includes('والدة')) {
                motherCol = colIdx;
                headerRowIdx = i;
            } else if ((str.includes('ناڤ') || str.includes('ناو') || str.includes('طالب') || str.includes('تلميذ') || str.includes('student') || str.includes('قوتابی') || str.includes('رباعي') || str.includes('ثلاثي') || str.includes('سیانی') || str.includes('چواری') || str.includes('تەواو') || str === 'الاسم' || str === 'اسم' || str === 'name') && !isSchoolOrgWord(str)) {
                if (!str.includes('دەیک') && !str.includes('دایک') && !str.includes('ام') && !str.includes('أم') && !str.includes('mother')) {
                    nameCol = colIdx;
                    headerRowIdx = i;
                }
            } else if (str.includes('پۆل') || str.includes('قۆناغ') || str.includes('صف') || str.includes('مرحلة') || str.includes('grade') || str.includes('class') || str.includes('stage')) {
                gradeCol = colIdx;
                headerRowIdx = i;
            } else if (str.includes('شعب') || str.includes('بەش') || str.includes('قسم') || str.includes('فرع') || str.includes('section') || str.includes('group')) {
                sectionCol = colIdx;
                headerRowIdx = i;
            }
        });

        if (nameCol !== -1) {
            headerRowIdx = i;
            break;
        }
    }

    const startRow = headerRowIdx !== -1 ? headerRowIdx + 1 : 0;
    const extractedLines = [];

    if (nameCol === -1) {
        const sampleRows = matrix.slice(startRow, startRow + 25);
        const colStats = {};

        sampleRows.forEach(row => {
            row.forEach((cell, idx) => {
                const s = String(cell || '').trim();
                if (!colStats[idx]) colStats[idx] = { wordCounts: [], isNames: 0, isOrg: 0 };
                if (s.length > 0) {
                    const words = s.split(/\s+/);
                    colStats[idx].wordCounts.push(words.length);
                    if (words.length >= 3 && !isSchoolOrgWord(s) && isNaN(s)) colStats[idx].isNames++;
                    if (isSchoolOrgWord(s)) colStats[idx].isOrg++;
                }
            });
        });

        let bestCol = -1;
        let bestScore = -1;
        for (const idx in colStats) {
            const st = colStats[idx];
            if (st.isOrg === 0 && st.isNames > bestScore) {
                bestScore = st.isNames;
                bestCol = parseInt(idx);
            }
        }
        if (bestCol !== -1) nameCol = bestCol;
    }

    for (let r = startRow; r < matrix.length; r++) {
        const row = matrix[r];
        if (!row || !Array.isArray(row)) continue;

        let studentName = '';
        let motherName = '';
        let grade = '';
        let section = '';

        if (nameCol !== -1) {
            studentName = String(row[nameCol] || '').trim();
            if (motherCol !== -1) motherName = String(row[motherCol] || '').trim();
            if (gradeCol !== -1) grade = String(row[gradeCol] || '').trim();
            if (sectionCol !== -1) section = String(row[sectionCol] || '').trim();
        } else {
            const nonEmpties = row.map(c => String(c || '').trim()).filter(c => c !== '');
            if (nonEmpties.length >= 4) {
                studentName = nonEmpties[0];
                motherName = nonEmpties[1];
                grade = nonEmpties[2];
                section = nonEmpties[3];
            } else if (nonEmpties.length === 3) {
                studentName = nonEmpties[0];
                grade = nonEmpties[1];
                section = nonEmpties[2];
            } else if (nonEmpties.length > 0) {
                studentName = nonEmpties[0];
                if (nonEmpties.length > 1) grade = nonEmpties[1];
                if (nonEmpties.length > 2) section = nonEmpties[2];
            }
        }

        if (studentName && studentName.length > 1 && !isSchoolOrgWord(studentName)) {
            let line = studentName;
            if (motherName && motherName.length > 1 && !isSchoolOrgWord(motherName) && isNaN(motherName)) {
                line += `\t${motherName}\t${grade || '-'}\t${section || '-'}`;
            } else {
                line += `\t${grade || '-'}\t${section || '-'}`;
            }
            extractedLines.push(line);
        }
    }

    return extractedLines;
}

// تسريع تجريد السوابق باستخدام الذاكرة
function stripPrefixes(text) {
    if (!document.getElementById('stripPrefixOpt').checked || !text) return text || '';
    if (prefixCache.has(text)) return prefixCache.get(text);

    const res = text.trim()
        .replace(/^(ال|أبو|ابو|أم|ام|ابن|بن|ملا|خان|شيخ|كاكا)\s+/g, '')
        .replace(/\s+(ال|أبو|ابو|أم|ام|ابن|بن|شيخ)\s+/g, ' ');
    prefixCache.set(text, res);
    return res;
}

// تسريع وتوحيد النصوص العربية والكردية (Memoized Deep Normalization)
function normalizeText(text) {
    if (!text) return '';
    if (normCache.has(text)) return normCache.get(text);

    const res = text.trim()
        .replace(/[\u064B-\u065F\u0670\u0640\u06D6-\u06ED]/g, '') // حركات وتشكيل وتطويل
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/[ةەھ]/g, 'ه')
        .replace(/[ىيیێۑئ]/g, 'ي') // توحيد كافة أشكال الياء (العربية، الكردية، الفارسية، والهمزة على نبرة)
        .replace(/[كک]/g, 'ك')     // توحيد الكاف
        .replace(/[ۆۇۈۋ]/g, 'و')   // توحيد الواو
        .replace(/[ڕ]/g, 'ر')      // توحيد الراء
        .replace(/[ڵ]/g, 'ل')      // توحيد اللام
        .replace(/\s+/g, ' ');

    normCache.set(text, res);
    return res;
}

// فحص تطابق الاسم بالكامل (4 من أصل 4 مقاطع) مع كشف الأخطاء الإملائية الطفيفة فقط واستبعاد الإخوة
function isDuplicateOrTypoName(a, b) {
    if (a === b) return true;
    if (!a || !b) return false;

    const wordsA = a.split(' ').filter(w => w.length > 0);
    const wordsB = b.split(' ').filter(w => w.length > 0);

    const minWords = Math.min(wordsA.length, wordsB.length);
    const maxWords = Math.max(wordsA.length, wordsB.length);

    // يجب أن تكون أطوال الأسماء متطابقة أو متقاربة جداً (الاسم الرباعي 4 مقاطع)
    if (Math.abs(wordsA.length - wordsB.length) > 1 || minWords < 2) {
        return false;
    }

    // 1. الاسم الأول للطالب: يجب أن يكون متطابقاً تماماً أو به خطأ إملائي طفيف جداً بحرف واحد فقط
    // لمنع جمع الإخوة مثل (أحمد وسارة، علي ومحمد)
    const firstA = wordsA[0];
    const firstB = wordsB[0];
    if (firstA !== firstB) {
        const firstDist = levenshteinDistance(firstA, firstB);
        if (firstDist > 1 || Math.min(firstA.length, firstB.length) < 3) {
            return false;
        }
    }

    // 2. مطابقة كافة المقاطع الأربعة (4 من أصل 4):
    let totalCharErrors = 0;
    for (let i = 0; i < minWords; i++) {
        const wA = wordsA[i];
        const wB = wordsB[i];
        if (wA !== wB) {
            const dist = levenshteinDistance(wA, wB);
            // لا يُسمح بأكثر من حرف واحد خطأ في أي مقطع من المقاطع
            if (dist > 1) {
                return false; // كلمة مختلفة تعني اسماً أو جداً مختلفاً تماماً
            }
            totalCharErrors += dist;
        }
    }

    // في كامل الاسم 4 من 4، لا يسمح بأكثر من خطأين طفيفين في الحروف
    return totalCharErrors <= 2;
}

// خوارزمية ليفنشتاين فائقة السرعة مع خفض استهلاك الذاكرة وتخطي الفروقات الكبيرة فوراً
const levBuf1 = new Int32Array(64);
const levBuf2 = new Int32Array(64);

function levenshteinDistance(s1, s2) {
    if (s1 === s2) return 0;
    const len1 = s1.length;
    const len2 = s2.length;
    if (len1 === 0) return len2;
    if (len2 === 0) return len1;
    if (Math.abs(len1 - len2) > 2) return 99; // خروج سريع وفوري عند الفارق الكبير

    const maxLen = len2 + 1;
    const prevRow = maxLen <= 64 ? levBuf1 : new Int32Array(maxLen);
    const currRow = maxLen <= 64 ? levBuf2 : new Int32Array(maxLen);

    for (let j = 0; j <= len2; j++) prevRow[j] = j;

    for (let i = 1; i <= len1; i++) {
        currRow[0] = i;
        const char1 = s1.charCodeAt(i - 1);
        for (let j = 1; j <= len2; j++) {
            const cost = (char1 === s2.charCodeAt(j - 1)) ? 0 : 1;
            currRow[j] = Math.min(
                prevRow[j] + 1,
                currRow[j - 1] + 1,
                prevRow[j - 1] + cost
            );
        }
        for (let j = 0; j <= len2; j++) prevRow[j] = currRow[j];
    }
    return currRow[len2];
}

function processNames() {
    const rawInput = document.getElementById('namesInput').value;
    const lines = rawInput.split('\n').map(line => line.trim()).filter(line => line.length > 0);
    
    if (lines.length === 0) {
        clearResultsArea();
        return;
    }

    studentPool = [];
    const sepMode = document.getElementById('dataSeparator').value;

    lines.forEach((line, index) => {
        let parts = [];
        let sep = ',';
        if (sepMode === 'auto') {
            if (line.includes('\t')) sep = '\t';
            else if (line.includes('،')) sep = '،';
            else if (line.includes(';')) sep = ';';
        } else {
            sep = sepMode === 'tab' ? '\t' : (sepMode === 'comma' ? ',' : ';');
        }

        parts = line.split(sep).map(p => p.trim());
        
        let name = parts[0] || '';
        let mother = '';
        let grade = currentLang === 'en' ? 'N/A' : (currentLang === 'ar' ? 'غير محدد' : 'دیارنەکری');
        let section = currentLang === 'en' ? 'N/A' : (currentLang === 'ar' ? 'غير محدد' : 'دیارنەکری');
        let guardian = '';

        if (parts.length >= 4) {
            mother = parts[1] || '';
            grade = parts[2] || grade;
            section = parts[3] || section;
            guardian = parts[4] || '';
        } else if (parts.length === 3) {
            grade = parts[1] || grade;
            section = parts[2] || section;
        } else if (parts.length === 2) {
            grade = parts[1] || grade;
        }

        if (name) {
            studentPool.push({ id: index, name, grade, section, mother, guardian });
        }
    });

    const relMode = document.getElementById('relativesSearchMode').value;
    const grandpaBox = document.getElementById('grandpaMatchBox');
    if (grandpaBox) {
        grandpaBox.style.display = (relMode === 'mother') ? 'none' : 'block';
    }

    renderEngine();
    updateHistoryArchive(rawInput);
}

function extractGrandfatherKey(name, depthMode, isStrip) {
    const normalized = normalizeText(isStrip ? stripPrefixes(name) : name);
    const words = normalized.split(' ').filter(w => w.length > 0);

    if (words.length < 2) {
        return { father: words[0] || '', grandpaKey: '' };
    }

    const father = words[1];

    let grandpaKey = '';
    if (depthMode === 'grandpa-3') {
        grandpaKey = words[2] || words[1];
    } else if (depthMode === 'grandpa-4') {
        grandpaKey = words[3] || words[2] || words[1];
    } else if (depthMode === 'all-ancestors') {
        grandpaKey = words.length > 2 ? words.slice(2).join(' ') : words[1];
    } else {
        if (words.length >= 4) {
            grandpaKey = words[2] + ' ' + words[3];
        } else if (words.length === 3) {
            grandpaKey = words[2];
        } else {
            grandpaKey = words[1];
        }
    }

    return { father, grandpaKey };
}

function renderEngine() {
    const matchType = document.getElementById('matchType').value;
    const isStrip = document.getElementById('stripPrefixOpt').checked;
    const relSearchMode = document.getElementById('relativesSearchMode').value;
    const grandpaDepth = document.getElementById('grandpaMatchDepth').value;
    
    // 1. كشف الإخوة الأشقاء
    const siblingGroups = {};
    let twinCount = 0;

    studentPool.forEach(student => {
        let key = '';
        if (student.guardian) {
            key = normalizeText(student.guardian);
        } else {
            const normalized = normalizeText(isStrip ? stripPrefixes(student.name) : student.name);
            const words = normalized.split(' ').filter(w => w.length > 0);
            
            if (matchType === 'all-except-first' && words.length > 1) {
                key = words.slice(1).join(' ');
            } else if (matchType === 'last-two' && words.length >= 2) {
                key = words.slice(-2).join(' ');
            } else if (matchType === 'last-one' && words.length >= 1) {
                key = words.slice(-1).join(' ');
            } else if (words.length > 1) {
                key = words.slice(1).join(' ');
            }
        }

        if (key) {
            if (!siblingGroups[key]) siblingGroups[key] = [];
            siblingGroups[key].push(student);
        }
    });

    siblingResults = [];
    let linkedSiblingsCount = 0;
    const siblingStudentIds = new Set();

    for (const key in siblingGroups) {
        if (siblingGroups[key].length > 1) {
            siblingResults.push({ sharedName: key, students: siblingGroups[key] });
            linkedSiblingsCount += siblingGroups[key].length;
            siblingGroups[key].forEach(s => siblingStudentIds.add(s.id));

            const gradesInGroup = siblingGroups[key].map(s => s.grade);
            const duplicateGrades = gradesInGroup.filter((item, index) => gradesInGroup.indexOf(item) !== index);
            if (duplicateGrades.length > 0) twinCount += duplicateGrades.length + 1;
        }
    }

    // 2. كشف الأقارب
    relativeResults = [];
    let totalRelativesMatched = 0;
    const relativeStudentIds = new Set();

    if (relSearchMode === 'father-grandpa' || relSearchMode === 'both') {
        const paternalRelativesMap = {};

        studentPool.forEach(student => {
            const { father, grandpaKey } = extractGrandfatherKey(student.name, grandpaDepth, isStrip);
            
            if (grandpaKey && grandpaKey.length > 1) {
                if (!paternalRelativesMap[grandpaKey]) paternalRelativesMap[grandpaKey] = {};
                if (!paternalRelativesMap[grandpaKey][father]) paternalRelativesMap[grandpaKey][father] = [];
                paternalRelativesMap[grandpaKey][father].push(student);
            }
        });

        for (const grandpaKey in paternalRelativesMap) {
            const fatherBranches = Object.keys(paternalRelativesMap[grandpaKey]);
            
            if (fatherBranches.length > 1) {
                const branches = {};
                let groupCount = 0;
                fatherBranches.forEach(father => {
                    branches[father] = paternalRelativesMap[grandpaKey][father];
                    groupCount += paternalRelativesMap[grandpaKey][father].length;
                    paternalRelativesMap[grandpaKey][father].forEach(s => relativeStudentIds.add(s.id));
                });

                totalRelativesMatched += groupCount;
                relativeResults.push({
                    type: 'paternal',
                    sharedKey: grandpaKey,
                    branches: branches,
                    totalCount: groupCount
                });
            }
        }
    }

    if (relSearchMode === 'mother' || relSearchMode === 'both') {
        const maternalRelativesMap = {};

        studentPool.forEach(student => {
            if (student.mother && student.mother.trim().length > 1) {
                const motherKey = normalizeText(isStrip ? stripPrefixes(student.mother) : student.mother);
                const normalizedStudentName = normalizeText(student.name);
                const words = normalizedStudentName.split(' ');
                const fatherOrBranch = words.length > 1 ? words.slice(1).join(' ') : student.name;

                if (!maternalRelativesMap[motherKey]) maternalRelativesMap[motherKey] = {};
                if (!maternalRelativesMap[motherKey][fatherOrBranch]) maternalRelativesMap[motherKey][fatherOrBranch] = [];
                maternalRelativesMap[motherKey][fatherOrBranch].push(student);
            }
        });

        for (const motherKey in maternalRelativesMap) {
            const branches = Object.keys(maternalRelativesMap[motherKey]);
            const totalMaternalStudents = Object.values(maternalRelativesMap[motherKey]).reduce((acc, curr) => acc + curr.length, 0);

            if (totalMaternalStudents > 1) {
                const branchData = {};
                branches.forEach(b => {
                    branchData[b] = maternalRelativesMap[motherKey][b];
                    maternalRelativesMap[motherKey][b].forEach(s => relativeStudentIds.add(s.id));
                });

                if (relSearchMode === 'mother' || branches.length > 1) {
                    totalRelativesMatched += totalMaternalStudents;
                    relativeResults.push({
                        type: 'maternal',
                        sharedKey: motherKey,
                        branches: branchData,
                        totalCount: totalMaternalStudents
                    });
                }
            }
        }
    }

    // 3. كشف الأشخاص الوحيدين
    solitaryResults = studentPool.filter(student => !siblingStudentIds.has(student.id) && !relativeStudentIds.has(student.id));

    // 4. كشف وتحديد الأسماء المتشابهة والمطابقة في المدرسة (بما فيها الأسماء المتشابهة بنسبة 85% فما فوق)
    const n = studentPool.length;
    const parent = Array.from({ length: n }, (_, i) => i);
    function find(i) {
        if (parent[i] === i) return i;
        return parent[i] = find(parent[i]);
    }
    function union(i, j) {
        const rootI = find(i);
        const rootJ = find(j);
        if (rootI !== rootJ) parent[rootI] = rootJ;
    }

    const normPool = studentPool.map(s => normalizeText(s.name));

    // خطوة 1: تجميع سريع للتطابق التام بعد توحيد النصوص
    const exactMap = new Map();
    for (let i = 0; i < n; i++) {
        const clean = normPool[i];
        if (clean.length > 1) {
            if (exactMap.has(clean)) {
                union(i, exactMap.get(clean));
            } else {
                exactMap.set(clean, i);
            }
        }
    }

    // خطوة 2: كشف الأسماء المتطابقة أو التي تحوي أخطاء إملائية طفيفة فقط (4 من أصل 4)
    for (let i = 0; i < n; i++) {
        const normA = normPool[i];
        if (normA.length <= 1) continue;
        for (let j = i + 1; j < n; j++) {
            if (find(i) === find(j)) continue; // مجمّعان مسبقاً
            const normB = normPool[j];
            if (normB.length <= 1) continue;

            if (isDuplicateOrTypoName(normA, normB)) {
                union(i, j);
            }
        }
    }

    const clusters = new Map();
    for (let i = 0; i < n; i++) {
        const root = find(i);
        if (!clusters.has(root)) clusters.set(root, []);
        clusters.get(root).push(studentPool[i]);
    }

    duplicateResults = [];
    clusters.forEach((students) => {
        if (students.length > 1) {
            duplicateResults.push({
                sharedName: students[0].name,
                students: students
            });
        }
    });

    // ترتيب الفرز
    const sortMode = document.getElementById('resultsSort').value;
    if (sortMode === 'count-desc') {
        siblingResults.sort((a, b) => b.students.length - a.students.length);
        relativeResults.sort((a, b) => b.totalCount - a.totalCount);
        solitaryResults.sort((a, b) => a.name.localeCompare(b.name));
        duplicateResults.sort((a, b) => b.students.length - a.students.length);
    } else {
        siblingResults.sort((a, b) => a.sharedName.localeCompare(b.sharedName));
        relativeResults.sort((a, b) => a.sharedKey.localeCompare(b.sharedKey));
        solitaryResults.sort((a, b) => a.name.localeCompare(b.name));
        duplicateResults.sort((a, b) => a.sharedName.localeCompare(b.sharedName));
    }

    // تحديث الإحصائيات
    document.getElementById('stat-total').textContent = studentPool.length;
    document.getElementById('stat-siblings').textContent = linkedSiblingsCount;
    document.getElementById('stat-relatives').textContent = totalRelativesMatched;
    document.getElementById('stat-twins').textContent = twinCount;
    document.getElementById('stat-solitary').textContent = solitaryResults.length;
    
    const totalDuplicateCount = duplicateResults.reduce((acc, g) => acc + g.students.length, 0);
    const statDup = document.getElementById('stat-duplicates');
    if (statDup) statDup.textContent = totalDuplicateCount;

    const mobBadge = document.getElementById('mobResultsBadge');
    if (mobBadge) {
        const totalFound = linkedSiblingsCount + totalRelativesMatched + solitaryResults.length + totalDuplicateCount;
        mobBadge.textContent = totalFound;
        if (totalFound > 0) mobBadge.classList.remove('hidden');
        else mobBadge.classList.add('hidden');
    }

    populateGradeFilter();
    displayResults();
}

